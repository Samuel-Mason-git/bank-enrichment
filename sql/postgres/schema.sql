-- bank-enrichment's tables in Postgres: the design in docs/server-move.md §4.
--
-- Three kinds of table:
--   history   transactions_raw, context_events, label_events. Only ever added
--             to, never edited: every arrival, context and label is a new row.
--             Bronze: the nightly dump takes the rows added since the last one.
--   settings  categories, roles, rules, proposals, reviews, subscriptions.
--             Edited in place. Bronze: a copy of the table on any day it changed.
--   gold      summaries: the figures each weekly/monthly summary sent.
--             Backed up like the settings.
-- and views, which store nothing: they're worked out from the tables every time
-- they're read, so they aren't backed up -- they come back with this file.
--
-- Only live links use ids (labels, rules, roles). Proposals, judge reviews and
-- rule suggestions keep category *names*: they record what was shown or decided
-- at the time, including categories since renamed or deleted.

-- ── Settings: the taxonomy ───────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS parent_categories (
    id          INTEGER   PRIMARY KEY,
    name        VARCHAR   NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL,
    -- A deleted category is archived rather than removed, so old labels still
    -- resolve to a name.
    archived_at TIMESTAMPTZ
);
-- Unique among live categories only, so an archived name can be used again.
CREATE UNIQUE INDEX IF NOT EXISTS parent_categories_live_name
    ON parent_categories (name) WHERE archived_at IS NULL;

CREATE TABLE IF NOT EXISTS subcategories (
    id          INTEGER   PRIMARY KEY,
    name        VARCHAR   NOT NULL,
    parent_id   INTEGER   NOT NULL REFERENCES parent_categories(id),
    created_at  TIMESTAMPTZ NOT NULL,
    archived_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX IF NOT EXISTS subcategories_live_name
    ON subcategories (parent_id, name) WHERE archived_at IS NULL;

-- What each category counts as. subcategory_id NULL = the whole parent.
CREATE TABLE IF NOT EXISTS category_roles (
    parent_id      INTEGER NOT NULL REFERENCES parent_categories(id),
    subcategory_id INTEGER REFERENCES subcategories(id),
    role           VARCHAR NOT NULL CHECK (role IN ('income', 'spend', 'investment', 'saving', 'transfer', 'excluded')),
    UNIQUE (parent_id, subcategory_id)
);

-- ── History ──────────────────────────────────────────────────────────────────

-- Every transaction exactly as Monzo sent it.
CREATE TABLE IF NOT EXISTS transactions_raw (
    id          VARCHAR   PRIMARY KEY,   -- Monzo's transaction id
    payload     JSONB     NOT NULL,      -- the webhook body, untouched
    received_at TIMESTAMPTZ NOT NULL
);

-- Every time context is given, changed, skipped, timed out or asked for. Each
-- row holds the full values, not a change: a transaction's context is its
-- latest row that isn't a request.
CREATE TABLE IF NOT EXISTS context_events (
    event_id            BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id              VARCHAR   NOT NULL REFERENCES transactions_raw(id),
    user_context        TEXT,
    skipped             BOOLEAN   NOT NULL DEFAULT FALSE,
    -- A date corrected in the dashboard; NULL = Monzo's own date.
    created_at_override TIMESTAMPTZ,
    --   telegram   a reply or a tap        rule      a rule's auto-context/skip
    --   dashboard  an edit in either one   timeout   no answer in time
    --   request    a card or nudge sent (no context: counts the follow-ups)
    --   migration  converted from the DuckDB setup
    source              VARCHAR   NOT NULL CHECK (source IN
        ('telegram', 'rule', 'dashboard', 'timeout', 'request', 'migration')),
    set_at              TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS context_events_by_txn ON context_events (txn_id, event_id);

-- Every time a category is set, changed or cleared. A transaction's label is
-- its latest row. subcategory_id NULL with a parent_id = parent only (what
-- deleting a subcategory leaves); both NULL = cleared.
CREATE TABLE IF NOT EXISTS label_events (
    event_id       BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id         VARCHAR   NOT NULL REFERENCES transactions_raw(id),
    parent_id      INTEGER   REFERENCES parent_categories(id),
    subcategory_id INTEGER   REFERENCES subcategories(id),
    source         VARCHAR   NOT NULL CHECK (source IN
        ('llm', 'rule', 'quick_tap', 'manual', 'judge', 'proposal', 'migration')),
    model          VARCHAR(255),
    confidence     DECIMAL(5,4),
    set_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (subcategory_id IS NULL OR parent_id IS NOT NULL)
);
CREATE INDEX IF NOT EXISTS label_events_by_txn ON label_events (txn_id, event_id);

-- ── Settings: everything else ────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS rules (
    id            INTEGER      PRIMARY KEY,
    name          VARCHAR(255) NOT NULL,
    match_field   VARCHAR(255) NOT NULL,
    match_type    VARCHAR(50)  NOT NULL DEFAULT 'contains',
    match_value   VARCHAR(255) NOT NULL,
    match_field_2 VARCHAR(255),
    match_type_2  VARCHAR(50),
    match_value_2 VARCHAR(255),
    auto_context  VARCHAR(255) NOT NULL DEFAULT '',
    auto_skip     BOOLEAN      NOT NULL DEFAULT FALSE,
    -- A fixed category: a match skips the classifier. NULL = none.
    subcategory_id INTEGER     REFERENCES subcategories(id),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE
);

-- Suggested rules waiting for a tap. Names as suggested; approving one makes a
-- rule pointing at that subcategory's id.
CREATE TABLE IF NOT EXISTS rule_suggestions (
    id           INTEGER      PRIMARY KEY,
    match_field  VARCHAR(255) NOT NULL,
    match_value  VARCHAR(255) NOT NULL,
    category     VARCHAR(255) NOT NULL,
    subcategory  VARCHAR(255) NOT NULL,
    txn_count    INTEGER      NOT NULL DEFAULT 0,
    auto_context VARCHAR(255) NOT NULL DEFAULT '',
    -- Shown on the card: why the classifier thought it worth a rule.
    llm_reasoning TEXT        NOT NULL DEFAULT '',
    -- declined: Claude judged it not worth a rule. Never sent, never asked again.
    status       VARCHAR(20)  NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'denied', 'declined')),
    proposed_at  TIMESTAMPTZ    NOT NULL,
    -- NULL until its Telegram card has gone out; the server sends any that haven't.
    sent_at      TIMESTAMPTZ,
    decided_at   TIMESTAMPTZ,
    UNIQUE (match_field, match_value)
);

-- The monthly "split or move this category" cards. One copy, replacing both
-- the local table and the server's. evidence_ids = exactly the transactions
-- shown on the card, so approving moves precisely what was reviewed.
CREATE TABLE IF NOT EXISTS taxonomy_proposals (
    id              INTEGER   PRIMARY KEY,
    action          VARCHAR   NOT NULL DEFAULT 'create' CHECK (action IN ('create', 'move')),
    parent_name     VARCHAR   NOT NULL,
    source_sub      VARCHAR   NOT NULL,
    target_parent   VARCHAR   NOT NULL DEFAULT '',   -- for 'move'
    proposed_sub    VARCHAR   NOT NULL,
    rationale       VARCHAR   NOT NULL,
    evidence_ids    JSONB     NOT NULL,
    -- Shown on the card: a few of those transactions, as one line each.
    examples        JSONB     NOT NULL DEFAULT '[]',
    status          VARCHAR   NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'approved', 'denied', 'applied', 'expired')),
    run_key         VARCHAR   NOT NULL,              -- the month, e.g. '2026-08'
    proposed_at     TIMESTAMPTZ NOT NULL,
    -- NULL until its Telegram card has gone out; the server sends any that haven't.
    sent_at         TIMESTAMPTZ,
    decided_at      TIMESTAMPTZ,
    applied_at      TIMESTAMPTZ,
    follow_up_count INTEGER   NOT NULL DEFAULT 0,
    last_nudged_at  TIMESTAMPTZ
);

-- The classifier's "new category?" cards. One copy, replacing both the local
-- table and the server's. txn_ids = the transactions it's holding back from the
-- classifier right now (today: transactions.pending_category_proposal_id). A
-- hold is released by emptying the list: when the proposal is applied, or turned
-- down with "None of these". "Try again" keeps it until the new proposal takes over.
CREATE TABLE IF NOT EXISTS category_proposals (
    id                   INTEGER   PRIMARY KEY,
    options              JSONB     NOT NULL,
    txn_ids              JSONB     NOT NULL DEFAULT '[]',
    -- Shown on the card: the held transactions, as one line each.
    examples             JSONB     NOT NULL DEFAULT '[]',
    status               VARCHAR   NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'selected', 'denied', 'applied', 'expired')),
    selected_option      INTEGER,
    -- "Try again" rather than "None of these": those options are avoided next
    -- time, but not blocked for good.
    regenerate_requested BOOLEAN   NOT NULL DEFAULT FALSE,
    proposed_at          TIMESTAMPTZ NOT NULL,
    -- NULL until its Telegram card has gone out; the server sends any that haven't.
    sent_at              TIMESTAMPTZ,
    decided_at           TIMESTAMPTZ,
    applied_at           TIMESTAMPTZ
);

-- What the placement judge made of each transaction, so it never asks twice.
-- category/subcategory = the placement judged, by name.
CREATE TABLE IF NOT EXISTS judge_reviews (
    txn_id       VARCHAR   PRIMARY KEY,
    merchant_key VARCHAR,
    category     VARCHAR   NOT NULL,
    subcategory  VARCHAR   NOT NULL,
    outcome      VARCHAR   NOT NULL CHECK (outcome IN ('approved', 'held', 'kept', 'changed')),
    reviewed_at  TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS subscriptions (
    id            INTEGER       PRIMARY KEY,
    name          VARCHAR(255)  NOT NULL,
    merchant_name VARCHAR(255),
    amount        DECIMAL(19,4) NOT NULL,
    frequency     VARCHAR(20)   NOT NULL CHECK (frequency IN ('weekly', 'fortnightly', 'monthly', 'annual')),
    active        BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ     NOT NULL
);

-- ── Gold ─────────────────────────────────────────────────────────────────────

-- The figures each weekly and monthly summary sent, and the record that it was
-- sent, so none goes out twice. Replaces weekly_summaries and monthly_summaries.
CREATE TABLE IF NOT EXISTS summaries (
    period         VARCHAR(5)    NOT NULL CHECK (period IN ('week', 'month')),
    period_key     VARCHAR(10)   NOT NULL,   -- '2026-W43' / '2026-10'
    total_spend    DECIMAL(19,4) NOT NULL,
    total_income   DECIMAL(19,4) NOT NULL,
    net            DECIMAL(19,4) NOT NULL,
    total_invested DECIMAL(19,4),
    total_saved    DECIMAL(19,4),
    sent_at        TIMESTAMPTZ     NOT NULL,
    PRIMARY KEY (period, period_key)
);

-- ── Columns added since a table was first created ────────────────────────────
-- CREATE TABLE IF NOT EXISTS does nothing to a table that's already there, so
-- every column added to an existing table is also added here. The server
-- applies this file on every start, so a deploy brings the database up to date.

ALTER TABLE rule_suggestions   ADD COLUMN IF NOT EXISTS llm_reasoning TEXT NOT NULL DEFAULT '';
ALTER TABLE rule_suggestions   ADD COLUMN IF NOT EXISTS sent_at TIMESTAMPTZ;
ALTER TABLE taxonomy_proposals ADD COLUMN IF NOT EXISTS examples JSONB NOT NULL DEFAULT '[]';
-- 'declined' added to rule_suggestions' statuses (a CHECK can't be widened in
-- place, so it's made again -- every row already passes the wider one).
ALTER TABLE rule_suggestions DROP CONSTRAINT IF EXISTS rule_suggestions_status_check;
ALTER TABLE rule_suggestions ADD CONSTRAINT rule_suggestions_status_check
    CHECK (status IN ('pending', 'approved', 'denied', 'declined'));
ALTER TABLE category_proposals ADD COLUMN IF NOT EXISTS examples JSONB NOT NULL DEFAULT '[]';

-- Every later version of a transaction: the other webhooks Monzo sends for it
-- (settlement, a merchant filled in, a final amount, a note), and what Monzo's
-- API said when the server looked it up. Only ever added to -- transactions_raw
-- keeps the first version exactly as it arrived, and this keeps the rest.
CREATE TABLE IF NOT EXISTS transaction_updates (
    update_id   BIGINT    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    txn_id      VARCHAR   NOT NULL REFERENCES transactions_raw(id),
    payload     JSONB     NOT NULL,
    --   webhook  another webhook for the same transaction
    --   api      Monzo's API, asked for it (a missing merchant)
    source      VARCHAR   NOT NULL CHECK (source IN ('webhook', 'api')),
    received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS transaction_updates_by_txn ON transaction_updates (txn_id, update_id);

-- ── Activity (for the dashboard's Activity page) ─────────────────────────────
-- What the app itself did, kept 90 days (the worker clears older rows). Not
-- history: losing it loses nothing about your money, so bronze leaves it out.

-- One row per pipeline run (process.py), whoever started it.
CREATE TABLE IF NOT EXISTS runs (
    run_id      BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at  TIMESTAMPTZ NOT NULL,
    finished_at TIMESTAMPTZ,
    --   running   still going (or stopped dead without saying)
    --   ok        every step worked     problems  a step failed, the rest ran
    --   skipped   another run was already going
    status      VARCHAR     NOT NULL CHECK (status IN ('running', 'ok', 'problems', 'skipped')),
    -- What it did: {"labelled": 3, "quick_taps": 1, ...}
    summary     JSONB       NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS runs_by_time ON runs (started_at);
-- Seconds per step ({"classifier": 12.4, ...}) and the container's memory at
-- the end ({"current_mb", "peak_mb" since the container started, "limit_mb"}).
ALTER TABLE runs ADD COLUMN IF NOT EXISTS steps  JSONB NOT NULL DEFAULT '{}';
ALTER TABLE runs ADD COLUMN IF NOT EXISTS memory JSONB NOT NULL DEFAULT '{}';

-- Every warning and error the server or the worker logged.
CREATE TABLE IF NOT EXISTS log_events (
    event_id   BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    logged_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    service    VARCHAR     NOT NULL CHECK (service IN ('server', 'worker')),
    level      VARCHAR     NOT NULL,   -- WARNING, ERROR, CRITICAL
    logger     VARCHAR,
    message    TEXT        NOT NULL,
    detail     TEXT                     -- the traceback, if there was one
);
CREATE INDEX IF NOT EXISTS log_events_by_time ON log_events (logged_at);

-- Each prompt's wording, once per version: the source of the function that
-- builds it (the fixed instructions; the payments and taxonomy are filled in
-- per call). llm_calls points here rather than storing every prompt whole.
CREATE TABLE IF NOT EXISTS prompt_versions (
    prompt_version VARCHAR     PRIMARY KEY,        -- module.function@fingerprint
    source         TEXT        NOT NULL,
    first_used_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Every call to Claude (src/pipeline/llm_calls.py): which prompt version and
-- payments went in (not the whole prompt -- its wording is in prompt_versions),
-- whether it worked, and what it cost at that day's prices. Kept for good.
CREATE TABLE IF NOT EXISTS llm_calls (
    call_id               BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    started_at            TIMESTAMPTZ NOT NULL,
    duration_ms           INTEGER,
    run_id                BIGINT,                  -- runs.run_id, when made during a run
    job                   VARCHAR     NOT NULL,    -- classify_parents, placement_judge, ...
    -- The function that built the prompt, with a fingerprint of its source:
    -- any edit to a prompt's wording shows up as a new version.
    prompt_version        VARCHAR,
    -- Whose model: everything is Anthropic's today, but the log (and its
    -- prices, keyed by model name) doesn't assume it stays that way.
    provider              VARCHAR     NOT NULL DEFAULT 'anthropic',
    model                 VARCHAR     NOT NULL,    -- as asked for
    response_model        VARCHAR,                 -- only if a different one answered (a fallback)
    params                JSONB       NOT NULL DEFAULT '{}',   -- max_tokens, thinking, ... (not the model)
    -- The prompt as sent isn't kept, only a fingerprint (the start of its
    -- sha256: identical prompts match) and its size.
    prompt_sha256         VARCHAR(16),
    prompt_chars          INTEGER,
    -- Kept only for a reply that couldn't be used: a usable one's answer is in
    -- the history it wrote (label_events, judge_reviews, the proposals).
    response_text         TEXT,
    thinking              TEXT,
    stop_reason           VARCHAR,
    input_tokens          INTEGER,                 -- uncached input
    cache_write_5m_tokens INTEGER,
    cache_write_1h_tokens INTEGER,
    cache_read_tokens     INTEGER,
    output_tokens         INTEGER,                 -- thinking included
    -- At that day's prices (llm_calls.PRICES, dated); NULL for an unpriced model.
    cost_usd              NUMERIC(12, 6),
    txn_ids               JSONB       NOT NULL DEFAULT '[]',   -- the payments it was about
    error                 TEXT,                    -- NULL: it worked
    retry_errors          JSONB,                   -- why each earlier attempt failed; NULL if none
    -- Whether the reply could be used: parsed at all, and how many of the
    -- items asked about it answered for.
    parsed                BOOLEAN,
    answered              INTEGER,
    expected              INTEGER,
    request_id            VARCHAR                  -- Anthropic's, for asking them about a call
);
CREATE INDEX IF NOT EXISTS llm_calls_by_time ON llm_calls (started_at);
CREATE INDEX IF NOT EXISTS llm_calls_by_txn ON llm_calls USING GIN (txn_ids);

-- Which rule gave a payment its context or label (NULL for anything else, and
-- for rule matches before this was recorded). No foreign key: the rule may
-- since have been deleted, and this is history.
ALTER TABLE context_events ADD COLUMN IF NOT EXISTS rule_id INTEGER;
ALTER TABLE label_events   ADD COLUMN IF NOT EXISTS rule_id INTEGER;

-- Every change to a setting -- rules, categories, roles, subscriptions --
-- with the row before and after. Written by the triggers below, so it can't
-- be missed whichever process made the change: the source is the name each
-- connects with (dashboard, server, worker).
CREATE TABLE IF NOT EXISTS settings_changes (
    change_id  BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    table_name VARCHAR     NOT NULL,
    action     VARCHAR     NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    before     JSONB,
    after      JSONB,
    source     VARCHAR
);
CREATE INDEX IF NOT EXISTS settings_changes_by_time ON settings_changes (changed_at);

-- An add keeps the whole new row and a delete the whole old one; an edit only
-- the fields that changed, before and after, plus the ones that say which row
-- it was (id, name, and the category links).
CREATE OR REPLACE FUNCTION record_settings_change() RETURNS trigger AS $$
DECLARE
    old_row JSONB := CASE WHEN TG_OP <> 'INSERT' THEN to_jsonb(OLD) END;
    new_row JSONB := CASE WHEN TG_OP <> 'DELETE' THEN to_jsonb(NEW) END;
    names   TEXT[] := ARRAY['id', 'name', 'parent_id', 'subcategory_id'];
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF old_row = new_row THEN
            RETURN NEW;  -- nothing actually changed
        END IF;
        SELECT jsonb_object_agg(key, value) INTO old_row FROM jsonb_each(to_jsonb(OLD))
         WHERE value IS DISTINCT FROM to_jsonb(NEW) -> key OR key = ANY(names);
        SELECT jsonb_object_agg(key, value) INTO new_row FROM jsonb_each(to_jsonb(NEW))
         WHERE value IS DISTINCT FROM to_jsonb(OLD) -> key OR key = ANY(names);
    END IF;
    INSERT INTO settings_changes (table_name, action, before, after, source)
    VALUES (TG_TABLE_NAME, TG_OP, old_row, new_row, NULLIF(current_setting('application_name', true), ''));
    RETURN COALESCE(NEW, OLD);
END;
$$ LANGUAGE plpgsql;

DO $$
DECLARE t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY['rules', 'parent_categories', 'subcategories', 'category_roles', 'subscriptions'] LOOP
        EXECUTE format('DROP TRIGGER IF EXISTS record_settings_change ON %I', t);
        EXECUTE format('CREATE TRIGGER record_settings_change AFTER INSERT OR UPDATE OR DELETE ON %I '
                       'FOR EACH ROW EXECUTE FUNCTION record_settings_change()', t);
    END LOOP;
END $$;

-- ── Views (silver: worked out on every read, nothing stored) ─────────────────

-- Dropped and made again every time, since a view stores nothing and Postgres
-- won't change the columns of one in place.
DROP VIEW IF EXISTS quick_categories, needs_label, needs_context, transaction_roles, transactions, transaction_current;

-- Every time is stored zone-aware (UTC). A database from before that had them
-- without a zone: they're converted here, once, read as UTC. (Times written
-- before the move to Postgres mixed London summer time and UTC, so some of
-- those old "set at" times are an hour out. Nothing is decided by them.)
DO $$
DECLARE col record;
BEGIN
    FOR col IN
        SELECT c.table_name, c.column_name FROM information_schema.columns c
        JOIN information_schema.tables t ON t.table_schema = c.table_schema AND t.table_name = c.table_name
        WHERE c.table_schema = current_schema() AND t.table_type = 'BASE TABLE'
          AND c.data_type = 'timestamp without time zone'
    LOOP
        EXECUTE format('ALTER TABLE %I ALTER COLUMN %I TYPE TIMESTAMPTZ USING %I AT TIME ZONE ''UTC''',
                       col.table_name, col.column_name, col.column_name);
    END LOOP;
END $$;
ALTER TABLE context_events ALTER COLUMN set_at SET DEFAULT now();
ALTER TABLE transaction_updates ALTER COLUMN received_at SET DEFAULT now();

-- Each transaction as it stands now, from all its versions: the newest one,
-- except that the merchant, the counterparty and the settled date come from the
-- newest version that has them. Monzo's webhooks arrive in no set order, and a
-- later one can carry merchant: null -- taking the newest naively would lose a
-- merchant an earlier one had.
CREATE OR REPLACE VIEW transaction_current AS
SELECT
    r.id,
    -- With nothing better in any version, each field is the newest version's
    -- own, so a transaction with one version reads exactly as it arrived.
    jsonb_set(jsonb_set(jsonb_set(
        newest.payload,
        '{data,merchant}',     COALESCE(merchant.value, newest.payload->'data'->'merchant', 'null'::jsonb)),
        '{data,counterparty}', COALESCE(counterparty.value, newest.payload->'data'->'counterparty', '{}'::jsonb)),
        '{data,settled}',      COALESCE(settled.value, newest.payload->'data'->'settled', '""'::jsonb))   AS payload
FROM transactions_raw r
CROSS JOIN LATERAL (
    SELECT v.payload FROM (
        SELECT r.payload, 0::BIGINT AS version
        UNION ALL
        SELECT u.payload, u.update_id FROM transaction_updates u WHERE u.txn_id = r.id
    ) v ORDER BY v.version DESC LIMIT 1
) newest
LEFT JOIN LATERAL (
    SELECT v.p->'data'->'merchant' AS value FROM (
        SELECT r.payload AS p, 0::BIGINT AS version
        UNION ALL
        SELECT u.payload, u.update_id FROM transaction_updates u WHERE u.txn_id = r.id
    ) v WHERE jsonb_typeof(v.p->'data'->'merchant') = 'object'
    ORDER BY v.version DESC LIMIT 1
) merchant ON TRUE
LEFT JOIN LATERAL (
    SELECT v.p->'data'->'counterparty' AS value FROM (
        SELECT r.payload AS p, 0::BIGINT AS version
        UNION ALL
        SELECT u.payload, u.update_id FROM transaction_updates u WHERE u.txn_id = r.id
    ) v WHERE COALESCE(v.p->'data'->'counterparty'->>'name', '') <> ''
    ORDER BY v.version DESC LIMIT 1
) counterparty ON TRUE
LEFT JOIN LATERAL (
    SELECT v.p->'data'->'settled' AS value FROM (
        SELECT r.payload AS p, 0::BIGINT AS version
        UNION ALL
        SELECT u.payload, u.update_id FROM transaction_updates u WHERE u.txn_id = r.id
    ) v WHERE COALESCE(v.p->'data'->>'settled', '') <> ''
    ORDER BY v.version DESC LIMIT 1
) settled ON TRUE;

-- One row per transaction, under the column names the old transactions table
-- had, so the dashboards and summaries read it the same way. Monzo's fields
-- come out of the transaction as it stands now (transaction_current: its newest
-- version, merchant and settlement filled in from any version that had them),
-- the way the old pipeline flattened them (amount from pence; '' dates as NULL).
-- raw_payload is that current version. parent_id/subcategory_id are extra, for
-- joining by id.
--
-- Its times are London time, without a zone: what a dashboard shows and what a
-- week or a month is counted by. (Stored, they're UTC; a payment at 00:30 BST
-- belongs to that day, not the one before.)
--
-- A labelled transaction's parent is its subcategory's parent *now*, not the
-- one recorded with the label, so moving a subcategory to another parent takes
-- its transactions with it. Only a parent-only label uses its own parent_id.
CREATE OR REPLACE VIEW transactions AS
SELECT
    r.id,
    (COALESCE((d.data->>'amount')::NUMERIC, 0) / 100)::DECIMAL(19,4) AS amount,
    COALESCE(d.data->>'currency', 'GBP')::VARCHAR(3)                AS currency,
    d.data->>'description'                                          AS description,
    d.data->>'category'                                             AS monzo_category,
    d.data->'merchant'->>'name'                                     AS merchant_name,
    d.data->'merchant'->>'category'                                 AS merchant_category,
    d.data->'counterparty'->>'name'                                 AS counterparty_name,
    (d.data->>'is_load')::BOOLEAN                                   AS is_load,
    COALESCE(c.created_at_override,
             NULLIF(d.data->>'created', '')::TIMESTAMPTZ) AT TIME ZONE 'Europe/London' AS created_at,
    NULLIF(d.data->>'settled', '')::TIMESTAMPTZ AT TIME ZONE 'Europe/London' AS settled_at,
    cur.payload                                                     AS raw_payload,
    c.user_context,
    COALESCE(c.skipped, FALSE)                                      AS skipped,
    r.received_at AT TIME ZONE 'Europe/London'                      AS received_at,
    c.set_at AT TIME ZONE 'Europe/London'                           AS enriched_at,
    pc.name                                                         AS llm_category,
    sc.name                                                         AS llm_subcategory,
    l.confidence                                                    AS llm_confidence,
    l.model                                                         AS llm_model,
    l.set_at AT TIME ZONE 'Europe/London'                           AS classified_at,
    (SELECT p.id FROM category_proposals p
      WHERE p.txn_ids ? r.id
      ORDER BY p.id LIMIT 1)                                        AS pending_category_proposal_id,
    pc.id                                                           AS parent_id,
    l.subcategory_id
FROM transactions_raw r
JOIN transaction_current cur ON cur.id = r.id
CROSS JOIN LATERAL (SELECT cur.payload->'data' AS data) d
LEFT JOIN LATERAL (
    SELECT * FROM context_events e
    WHERE e.txn_id = r.id AND e.source <> 'request'
    ORDER BY e.event_id DESC LIMIT 1
) c ON TRUE
LEFT JOIN LATERAL (
    SELECT * FROM label_events e
    WHERE e.txn_id = r.id
    ORDER BY e.event_id DESC LIMIT 1
) l ON TRUE
LEFT JOIN subcategories sc ON sc.id = l.subcategory_id
LEFT JOIN parent_categories pc ON pc.id = COALESCE(sc.parent_id, l.parent_id);

-- Built-in default role by category name, used when no role is set.
CREATE OR REPLACE FUNCTION default_role_for_parent(parent_name VARCHAR) RETURNS VARCHAR
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE parent_name
        WHEN 'Income' THEN 'income'
        WHEN 'Investments' THEN 'investment'
        WHEN 'Transfers' THEN 'transfer'
    END
$$;

-- Each transaction's role: the subcategory's, else the parent's, else the
-- built-in default, else spend, else (only if unclassified) by the amount's sign.
CREATE OR REPLACE VIEW transaction_roles AS
SELECT t.*, COALESCE(
    sub_role.role,
    parent_role.role,
    default_role_for_parent(t.llm_category),
    CASE WHEN t.llm_category IS NOT NULL THEN 'spend' END,
    CASE WHEN t.amount >= 0 THEN 'income' ELSE 'spend' END
) AS role
FROM transactions t
LEFT JOIN category_roles sub_role ON sub_role.subcategory_id = t.subcategory_id
LEFT JOIN category_roles parent_role
    ON parent_role.parent_id = t.parent_id AND parent_role.subcategory_id IS NULL;

-- Transactions waiting for an answer: no context yet, not even a timeout. Drives
-- the Telegram card and its follow-ups, so its times stay exact (zone-aware):
-- they're compared with "an hour ago", not shown.
CREATE OR REPLACE VIEW needs_context AS
SELECT
    r.id,
    r.received_at,
    COUNT(e.event_id)  AS request_count,
    MAX(e.set_at)      AS last_requested_at
FROM transactions_raw r
LEFT JOIN context_events e ON e.txn_id = r.id AND e.source = 'request'
WHERE NOT EXISTS (
    SELECT 1 FROM context_events x WHERE x.txn_id = r.id AND x.source <> 'request'
)
GROUP BY r.id, r.received_at;

-- The classifier's to-do list: context settled, not skipped, not fully
-- labelled, and not held back by a category proposal.
CREATE OR REPLACE VIEW needs_label AS
SELECT t.*
FROM transactions t
WHERE t.enriched_at IS NOT NULL
  AND NOT t.skipped
  AND (t.llm_category IS NULL OR t.llm_subcategory IS NULL)
  AND t.pending_category_proposal_id IS NULL;

-- The quick-tap buttons on a card: the 10 most-used categories overall
-- (merchant_name NULL), plus each of the 50 busiest merchants' top 3. A
-- merchant is merchant_name, falling back to the counterparty (direct debits
-- and transfers rarely have a merchant). rank starts at 0. subcategory_id is
-- what a button carries, so a tap files exactly the category shown even if
-- the list has moved on since the card was sent.
CREATE OR REPLACE VIEW quick_categories AS
WITH labelled AS (
    SELECT COALESCE(NULLIF(merchant_name, ''), NULLIF(counterparty_name, '')) AS merchant,
           subcategory_id, llm_category AS category, llm_subcategory AS subcategory
    FROM transactions
    WHERE subcategory_id IS NOT NULL
),
overall AS (
    SELECT subcategory_id, category, subcategory,
           ROW_NUMBER() OVER (ORDER BY COUNT(*) DESC, category, subcategory) AS n
    FROM labelled
    GROUP BY subcategory_id, category, subcategory
),
busiest AS (
    SELECT merchant FROM labelled
    WHERE merchant IS NOT NULL
    GROUP BY merchant
    ORDER BY COUNT(*) DESC, merchant
    LIMIT 50
),
per_merchant AS (
    SELECT l.merchant, l.subcategory_id, l.category, l.subcategory,
           ROW_NUMBER() OVER (PARTITION BY l.merchant
                              ORDER BY COUNT(*) DESC, l.category, l.subcategory) AS n
    FROM labelled l
    JOIN busiest b ON b.merchant = l.merchant
    GROUP BY l.merchant, l.subcategory_id, l.category, l.subcategory
)
SELECT NULL::VARCHAR AS merchant_name, subcategory_id, category, subcategory, n - 1 AS rank
FROM overall WHERE n <= 10
UNION ALL
SELECT merchant, subcategory_id, category, subcategory, n - 1
FROM per_merchant WHERE n <= 3;
